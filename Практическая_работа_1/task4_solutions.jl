# Задача 4. "Разведение растворов"
# a - объём 60%-ного раствора (л), b - объём 20%-ного раствора (л)
# Система уравнений:
#   a + b = 10                    (общий объём смеси)
#   0.6a + 0.2b = 0.4 * 10        (количество чистой кислоты)

# Записываем систему в матричном виде: A * [a, b] = B
A = [1.0 1.0;
     0.6 0.2]
B = [10.0, 0.4 * 10]

# Решаем систему (оператор \ решает линейную систему)
a, b = round.(A \ B, digits=2)

