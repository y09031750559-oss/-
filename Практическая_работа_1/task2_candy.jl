# Задача 2. "Смесь конфет"
# x - масса конфет "А" (кг), y - масса конфет "Б" (кг)
# Система неравенств:
#   x + y ≥ 100              (всего не менее 100 кг)
#   300x + 500y ≤ 40000      (бюджет не более 40 000 руб.)
#   x ≥ 50                   (конфет "А" не менее 50 кг)
#   y ≥ 0                    (масса не может быть отрицательной)

# Подключаем библиотеку Plots для построения графиков
using Plots

# Функция-проверка: подходит ли вариант закупки (x, y) под все условия
is_feasible(x, y) = (x + y >= 100) && (300x + 500y <= 40000) && (x >= 50) && (y >= 0)

function plot_candy_problem()
    # Выражаем y из граничных уравнений
    y_mass(x)   = 100 - x                 # x + y = 100
    y_budget(x) = (40000 - 300x) / 500    # 300x + 500y = 40000

    # Диапазон значений x от 0 до 150 кг с шагом 0.5
    x_range = 0:0.5:150

    # Рисуем граничную прямую по массе
    plot(x_range, y_mass.(x_range),
         linewidth=2,
         title="Область допустимых вариантов закупки",
         xlabel="Конфеты \"А\" x (кг)",
         ylabel="Конфеты \"Б\" y (кг)",
         label="x + y = 100",
         legend=:topright,
         xlims=(0, 150), ylims=(0, 120))

    # Граничная прямая по бюджету
    plot!(x_range, y_budget.(x_range), linewidth=2, label="300x + 500y = 40000")

    # Вертикальная прямая x = 50
    vline!([50], linewidth=2, label="x = 50")

    # Закрашиваем область допустимых решений (треугольник)
    vx = [50, 100, 400/3]
    vy = [50, 0, 0]
    plot!(Shape(vx, vy), fillcolor=:green, fillalpha=0.3,
          linecolor=:green, label="Допустимая область")

    # Отмечаем вершины области
    scatter!(vx, vy, color=:red, markersize=6,
             label="Вершины: (50; 50), (100; 0), (133,3; 0)")

    return plot!()
end

# Выводим модель и проверяем несколько вариантов закупки
println("Задача 2 - Смесь конфет:")
println("Система неравенств:")
println("  x + y ≥ 100")
println("  300x + 500y ≤ 40000")
println("  x ≥ 50,  y ≥ 0")
for (x, y) in [(50, 50), (80, 30), (70, 40), (120, 0)]
    println("Вариант x = $x кг, y = $y кг: ",
            is_feasible(x, y) ? "подходит" : "не подходит",
            " (масса $(x + y) кг, стоимость $(300x + 500y) руб.)")
end

# Рисуем график
plot_candy_problem()
